"""Application contracts; production adapters can replace SQLite and model routing."""

from contextlib import AbstractContextManager
from typing import Any, Protocol

from .domain import Classification, Intent, Scope


class RepositoryPort(Protocol):
    def atomic(self) -> AbstractContextManager: ...
    def get(self, scope: Scope, kind: str, key: str) -> dict | None: ...
    def list(self, scope: Scope, kind: str) -> list[dict]: ...
    def put(self, scope: Scope, kind: str, key: str, payload: dict) -> None: ...
    def delete(self, scope: Scope, kind: str) -> None: ...
    def audit(self, scope: Scope, action: str, reference: str) -> None: ...


class IntelligencePort(Protocol):
    def classify(self, merchant: str) -> Classification | None: ...
    def intent(
        self, message: str, month: str, previous: Any = None, *, consent: bool = True
    ) -> tuple[Intent, str]: ...
